/// Narrative role of a Story Builder prompt in the Hero's story arc.
///
/// Used by the deterministic catalog (SB.3) and later structure mapping (SB.4).
/// Distinct from Discovery NarrativeTheme and Story catalog classification.
enum StoryBuilderNarrativeRole {
  beginning,
  challenge,
  importance,
  struggle,
  stakes,
  turningPoint,
  decision,
  action,
  outcome,
  reflection,
  message,
}
